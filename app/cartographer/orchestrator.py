"""
Operator-invoked analysis: the full chain as PSE missions (C8).

`analyze_patient(path)` runs, end to end, on one local GGUF:
  L1 anatomy (the engine's sealed L1 mission, once per model)  →  J-space basis for every
  layer (C5, one backward pass per calibration prompt)  →  cartography session over a prompt
  battery (C6)  →  drift/summary (C7)  →  three-register report (C9)  →  sealed into the
  dossier as a `cartography` run.

The cartography run is a PSE unit mission like every other: a compute budget (one step per
prompt), priors per (model family, depth) that a finding must MOVE to count as learning,
theta, and the three-layer seal. A run the contribution gate refuses is still shown (its
numbers are real), but it does not enter the dossier as sealed knowledge.

The battery is either a default ambiguous-prompt set (good for eliciting ignition) or, in
ACTIVE CARTOGRAPHER mode, generated by the spokesperson from the previous readout — the
working model steering the mapping of the patient.
"""
from __future__ import annotations

import json
import math
import os

from pse_a.core.capability import semaphore
from pse_a.core.cost import MachineRates
from pse_a.core.source.canonical import build_map
from pse_a.core.source.gguf import open_gguf
from pse_a.shell import prognostics as pg
from pse_a.shell.lens_missions import load_runtime
from pse_a.shell.shared_lib import SealRefused, Welford
from pse_a.shell.unit import Budget, Unit

from . import drift as drift_mod
from .basis import estimate_bases
from .report import Reporter
from .session import CartographySession

DEFAULT_BATTERY = [
    "The bank by the river was",                 # lexical ambiguity
    "She saw the man with the telescope",        # attachment ambiguity
    "The old man the boat",                       # garden-path
    "Water is made of hydrogen and",             # factual completion
    "2 + 2 =",                                     # arithmetic
    "The opposite of hot is",                     # semantic
    "Once upon a time there was a",              # narrative
    "def add(a, b): return",                       # code
]


class NotAvailable(RuntimeError):
    """AZ-2: a reason known at L0 — said before anything runs."""


def active_probes(voice, prev_readout, n: int = 1) -> list:
    """Active cartographer: the spokesperson proposes the next probe from the last readout."""
    if not (voice and voice.has_voice()) or prev_readout is None:
        return []
    lr = drift_mod.representative_layer(prev_readout)
    concepts = ", ".join(lbl for lbl, _ in (lr.top_concepts[:8] if lr else []))
    try:
        msgs = [{"role": "user",
                 "content": f"A language model, at its committing layer, is currently "
                            f"holding these concepts in mind: {concepts}. Propose {n} short "
                            f"prompt(s), one per line, that would test whether a nearby but "
                            f"different concept lights up. Output only the prompt(s)."}]
        txt = voice.backend.complete("You design short probe prompts for a model-analysis "
                                     "tool. Output only the prompts.", msgs, max_tokens=300)
        return [l.strip("-•*0123456789. ").strip() for l in txt.splitlines() if l.strip()][:n]
    except Exception:
        return []


def check_patient(gguf_path: str, ram_bytes: int, rates: MachineRates):
    """Model card + semaphore for the patient; raises NotAvailable when L4 cannot run."""
    g = open_gguf(gguf_path)
    mm = build_map(g)
    caps = semaphore(g, mm, rates, ram_bytes)
    if not caps.layers.get("L4"):
        raise NotAvailable(caps.blockers.get("L4", "J-space is not available for this model"))
    return g, mm, caps


class Orchestrator:
    def __init__(self, lib, voice, data_root: str):
        self.lib = lib
        self.voice = voice
        self.root = data_root
        self.reporter = Reporter(voice)

    def _has_sealed_l1(self, mh: str) -> bool:
        return any(r["kind"] == "l1_sweep" for r in self.lib.runs_of(mh, "sealed"))

    def analyze_patient(self, gguf_path: str, battery=None, active=False, n_probes: int = 128,
                        calib=None, layers=None, run_l1: bool = True, progress=None,
                        rates: MachineRates | None = None, ram_bytes: int | None = None) -> dict:
        from pse_a.core.runtime.numpy_rt import ram_bytes as _ram
        prog = progress or (lambda stage, i, n: None)
        rates = rates or MachineRates(gemm_gflops=20.0, eig_c=1e-9)
        g, mm, caps = check_patient(gguf_path, ram_bytes or _ram(), rates)
        mh = g.model_hash()
        name = os.path.basename(gguf_path)
        family = f"{mm.architecture}-d{mm.d_model}"

        # --- L1 anatomy (CPU, sealed engine mission; once per model) ---
        l1_note = "already in the dossier"
        if run_l1 and not self._has_sealed_l1(mh):
            from pse_a.shell.l1_mission import run_l1 as _run_l1
            n_mat = len([n for n in mm.weight_matrices()
                         if mm.roles[n].role_class != "embedding"])
            cnt = {"i": 0}

            def l1_prog(msg):
                cnt["i"] = min(cnt["i"] + 10, n_mat)
                prog("anatomy (L1)", cnt["i"], n_mat)
            r1 = _run_l1(gguf_path, self.lib, progress=l1_prog)
            l1_note = "sealed" if r1.get("sealed") else "measured, not sealed"
        l1_sum = self._l1_summary(mh)

        # --- enter the patient (numpy runtime) ---
        prog("loading the patient", 0, 1)
        rt = load_runtime(gguf_path)
        layers = list(layers or range(rt.n_layers))      # dense: ignition needs <= 2 layers
        calib = list(calib or DEFAULT_BATTERY)

        # --- J-space basis for every mapped layer (C5) ---
        bases, cached = estimate_bases(rt, layers, calib, self.root, n_probes,
                                       progress=lambda i, n: prog("J-space basis", i, n),
                                       extra_texts=battery or DEFAULT_BATTERY)

        # --- cartography session as a unit mission (C6) ---
        battery = list(battery or DEFAULT_BATTERY)
        cfg = {"kind": "cartography", "layers": layers, "n_probes": n_probes,
               "calib": calib, "battery": battery, "active": bool(active)}
        run = self.lib.open_run(mh, "cartography", cfg, {"seed": 0})
        unit = Unit(f"cart-{run.run_id}", {"state": "prompts", "model": mh,
                                           "action": "read J-space", "outcome": "trajectory"},
                    Budget(total=len(battery)), seed=0)
        sess = CartographySession(rt, self.root, bases, run_id=run.run_id)
        pending, local = [], {}

        def learn(r, prev):
            moved = 0
            lr = drift_mod.representative_layer(r)
            vals = {}
            if lr is not None:
                d = f"d{round(lr.layer / max(rt.n_layers - 1, 1) * 4) / 4:.2f}"
                vals[f"{family}/cartography/{d}/var_frac"] = lr.var_frac
            if r.ignition_layer is not None:
                vals[f"{family}/cartography/ignition_depth"] = r.ignition_layer / max(rt.n_layers - 1, 1)
            if prev is not None:
                vals[f"{family}/cartography/drift"] = drift_mod.drift([prev, r])[0]
            for key, v in vals.items():
                if not math.isfinite(v):
                    continue
                novel, z = self.lib.test_prior(key, float(v), local=local.get(key))
                pending.append((key, float(v)))
                local.setdefault(key, Welford()).push(float(v))
                if novel:
                    self.lib.record_registry(run.run_id, "cartography", key, float(v),
                                             z if math.isfinite(z) else 1e9)
                    unit.absorb(key)
                    moved += 1
            unit.step(moved)
            self.lib.progress(run.run_id, len(unit.theta_series), unit.budget.total,
                              unit.theta, r.prompt[:40])

        queue = battery[:2] if active else list(battery)
        fed = []
        while queue and len(fed) < len(battery):
            p = queue.pop(0)
            prev = sess.readouts[-1] if sess.readouts else None
            r = sess.readout(p)
            fed.append(p)
            learn(r, prev)
            prog("reading prompts", len(fed), len(battery))
            if active and not queue:
                queue += active_probes(self.voice, r, n=1) or battery[len(fed):len(fed) + 1]
        results_path = sess.write_results()

        # --- drift + report (C7 + C9) ---
        summ = drift_mod.summary(sess.readouts)
        bundle = {
            "model": {"display_name": name, "architecture": mm.architecture,
                      "n_layers": mm.n_layers, "model_hash": mh, "path": gguf_path},
            "l1": l1_sum, "l1_note": l1_note, "session_summary": summ,
            "layers_mapped": sorted(bases), "basis_cached": cached, "n_probes": n_probes,
            "probes": next(iter(bases.values())).labels,
            "results_path": str(results_path), "readouts": sess.readouts,
            "prompts": fed, "active": bool(active),
        }
        prog("writing the report", 0, 1)
        facts = self.reporter.facts_block(bundle)
        bundle["expert_note"] = self.reporter.expert_note("J-space cartography", facts)
        bundle["narodski_report"] = self.reporter.narodski_report(bundle)
        bundle["voice"] = self.voice.backend.name if self.voice.has_voice() else None

        # --- seal the cartography run into the dossier ---
        art = sess.payload()
        art.update({"model": name, "n_layers": mm.n_layers, "summary": summ,
                    "battery": fed, "active": bool(active), "l1": l1_sum})
        self.lib.attach(run, "cartography.json", json.dumps(art, default=float).encode())
        self.lib.attach(run, "report.json", json.dumps({
            "facts": facts, "expert_note": bundle["expert_note"],
            "plain_report": bundle["narodski_report"], "voice": bundle["voice"]}).encode())
        self.lib.attach(run, "theta_series.json", json.dumps(unit.theta_series).encode())
        spec = {"action": "cartography", "prompts": len(fed)}
        out = {"action": "cartography", "prompts": len(sess.readouts)}
        try:
            self.lib.seal(run, out, spec, unit.theta_series, len(unit.registry),
                          self.lib.registry_baseline(mh, "cartography"), pending_priors=pending)
            bundle["sealed"] = True
        except SealRefused as e:
            self.lib.record_death(run.run_id, str(e), len(unit.registry))
            bundle["sealed"] = False
            bundle["refused"] = pg.refusal(pg.gate_reasons(str(e))) if pg.gate_reasons(str(e)) \
                else str(e)
        from pse_a.shell.physician import review
        bundle["prognoses"] = review(self.lib, mh, "cartography")
        bundle["run_id"] = run.run_id
        bundle["registry"] = len(unit.registry)
        return bundle

    def _l1_summary(self, mh: str) -> dict:
        runs = [r for r in self.lib.runs_of(mh, "sealed") if r["kind"] == "l1_sweep"]
        if not runs:
            return {}
        rep, _ = self.lib.artifact_json(runs[0]["run_id"], "l1_report.json")
        M = rep["matrices"]
        return {"n": len(M),
                "trained": sum(1 for m in M if m["regime"] in ("heavy_tailed", "mixed")),
                "random": sum(1 for m in M if m["regime"] == "random_like")}
