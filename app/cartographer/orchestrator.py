"""
Operator-invoked analysis: the full chain as PSE missions (C8).

`analyze_patient(path)` runs, end to end, on one local GGUF:
  L1 anatomy (via the engine's MissionRunner)  →  J-space basis per mapped layer (C5)  →
  cartography session over a prompt battery (C6)  →  drift/summary (C7)  →  three-layer
  report (C9)  →  sealed into the dossier.

Each stage is a unit mission with a compute budget; results seal through the engine's
three-layer verification. The battery is either a default ambiguous-prompt set (good for
eliciting ignition) or, in ACTIVE CARTOGRAPHER mode, generated by the spokesperson from the
previous readout — the working model steering the mapping of the patient.

Torch-backed stages import lazily; on a torch-less box the function raises a clear error
that the GUI turns into the copy-paste install instructions (C4).
"""
from __future__ import annotations

from pse_a.shell.missions import MissionRunner
from pse_a.shell.units import Mission, make_unit

from . import drift as drift_mod
from .basis import estimate_basis
from .report import Reporter
from .session import CartographySession

DEFAULT_BATTERY = [
    "The bank by the river was",                 # lexical ambiguity
    "She saw the man with the telescope",        # attachment ambiguity
    "The old man the boat",                       # garden-path
    "Water is made of hydrogen and",             # factual completion
    "2 + 2 =",                                     # arithmetic
    "The opposite of hot is",                     # semantic
    "Once upon a time there was a",              # narrative
    "def add(a, b): return",                       # code
]


def choose_layers(n_layers: int, k: int = 6) -> list:
    """Map a spread of layers (cheap) rather than all — one basis estimate per layer."""
    if n_layers <= k:
        return list(range(n_layers))
    step = max(1, n_layers // k)
    return list(range(0, n_layers, step))[:k]


def active_probes(psel, prev_readout, n: int = 1) -> list:
    """Active cartographer: the spokesperson proposes the next probe from the last readout."""
    if not (psel and psel.backend and psel.backend.available()) or prev_readout is None:
        return []
    concepts = ", ".join(lbl for lbl, _ in
                         (drift_mod.representative_layer(prev_readout).top_concepts[:8]
                          if drift_mod.representative_layer(prev_readout) else []))
    try:
        msgs = [{"role": "user",
                 "content": f"A language model, at its committing layer, is currently "
                            f"holding these concepts in mind: {concepts}. Propose {n} short "
                            f"prompt(s), one per line, that would test whether a nearby but "
                            f"different concept lights up. Output only the prompt(s)."}]
        txt = psel.backend.complete(psel._system(), msgs, max_tokens=200)
        return [l.strip("-• ").strip() for l in txt.splitlines() if l.strip()][:n]
    except Exception:
        return []


class Orchestrator:
    def __init__(self, shared_lib, psel):
        self.lib = shared_lib
        self.psel = psel
        self.runner = MissionRunner(shared_lib)
        self.reporter = Reporter(psel)

    def analyze_patient(self, gguf_path: str, layers=None, battery=None,
                        active=False, run_id="run", progress=None, calib=None) -> dict:
        from pse_a.core.gguf_source import GGUFSource
        from pse_a.core.runtime_torch import TorchRuntime
        import os

        # --- L1 anatomy (CPU, engine mission) ---
        src = GGUFSource(gguf_path)
        mm = src.config()
        mm.display_name = os.path.basename(gguf_path)
        dossier = self.lib.register_model(mm)
        l1_rec = self.runner.run_l1(src, dossier)
        l1_report = l1_rec._live_report
        l1_sum = {
            "n": len(l1_report),
            "trained": sum(1 for h in l1_report.values() if h.verdict == "trained"),
            "random": sum(1 for h in l1_report.values() if h.verdict == "random-like"),
        }

        # --- enter the patient (torch) ---
        gguf = gguf_path if gguf_path.endswith(".gguf") else None
        rt = TorchRuntime(os.path.dirname(gguf_path) if gguf else gguf_path,
                          gguf_file=(os.path.basename(gguf_path) if gguf else None))

        # --- J-space basis per mapped layer (C5) ---
        layers = layers or choose_layers(rt.n_layers)
        calib = calib or DEFAULT_BATTERY
        unit_b = make_unit("unit_C5", "L4_jlens",
                           Mission("resid stream", "estimate basis", "J-space rows"),
                           ctx={"jlens_prompts": len(calib)})
        bases = {}
        for L in layers:
            if progress:
                progress("basis", L, len(layers))
            bases[L] = estimate_basis(rt, mm, L, calib, self.lib, mm.model_hash,
                                      unit=unit_b)

        # --- cartography session (C6) ---
        battery = list(battery or DEFAULT_BATTERY)
        unit_s = make_unit("unit_C6", "L2_lens",
                           Mission("prompts", "read J-space", "trajectory"),
                           ctx={"N_max": 10000})
        sess = CartographySession(rt, mm, self.lib, mm.model_hash, bases, run_id=run_id)
        if active:                                    # active cartographer loop
            outs = []
            prompts = battery[:2]
            for _ in range(len(battery)):
                if not prompts:
                    break
                p = prompts.pop(0)
                r = sess.readout(p)
                outs.append(r)
                prompts += active_probes(self.psel, r, n=1)
            sess.write_results()
        else:
            sess.run_battery(battery, unit=unit_s,
                             progress=(lambda i, n, p: progress("session", i, n))
                             if progress else None)

        # --- drift + report (C7 + C9) ---
        summ = drift_mod.summary(sess.readouts)
        bundle = {
            "model": {"display_name": mm.display_name, "architecture": mm.architecture,
                      "n_layers": mm.n_layers, "model_hash": mm.model_hash},
            "l1": l1_sum, "session_summary": summ,
            "layers_mapped": sorted(bases),
            "results_path": str(sess.results_path()),
            "readouts": sess.readouts,
        }
        bundle["expert_note"] = self.reporter.expert_note("J-space cartography",
                                                          self.reporter._facts_block(bundle))
        bundle["narodski_report"] = self.reporter.narodski_report(bundle)

        # --- seal the cartography run into the dossier ---
        art = self.lib.make_artifact({"summary": summ, "layers": sorted(bases),
                                      "results_path": bundle["results_path"]})
        from pse_a.shell.dossier import RunRecord
        rec = RunRecord(run_id=f"cart_{run_id}", timestamp=self.lib.now(),
                        layer="J-space", config_hash=mm.model_hash or "",
                        seeds={"battery": "default" if battery is DEFAULT_BATTERY else "custom"},
                        budget_spent=unit_s.budget.spent,
                        artifacts={"cartography": art})
        unit_s.outcome_ok = len(sess.readouts) > 0
        self.lib.seal_run(dossier, rec, unit_s)
        bundle["sealed"] = rec.sealed
        return bundle
